export function getAllExercises(
  customExercises: ExerciseItem[],
  exerciseNotes: Record<string, string>
): ExerciseItem[] {
  return [...SYSTEM_EXERCISES, ...customExercises].map((ex) => ({
    ...ex,
    personalNotes: exerciseNotes[ex.slug] ?? ex.personalNotes ?? '',
  }));
}

export function findExerciseBySlug(
  slug: string,
  customExercises: ExerciseItem[] = []
): ExerciseItem | undefined {
  return [...SYSTEM_EXERCISES, ...customExercises].find((e) => e.slug === slug);
}

/**
 * Dado un ejercicio objetivo y el equipamiento activo, devuelve el propio ejercicio
 * si es compatible o busca automáticamente la mejor sustitución funcional disponible
 * que conserve el mismo patrón de movimiento y respete el nivel de seguridad.
 */
export function resolveCompatibleExercise(
  preferredSlug: string,
  equipment: EquipmentItem[],
  customExercises: ExerciseItem[] = [],
  allowAdvancedCore = false
): { exercise: ExerciseItem; substitutedFrom?: string } {
  const catalog = [...SYSTEM_EXERCISES, ...customExercises];
  const activeSet = getActiveEquipmentSet(equipment);
  const preferred = catalog.find((e) => e.slug === preferredSlug) ?? catalog[0]!;

  // Regla de seguridad abdominal: no prescribir rueda abdominal automáticamente sin base previa
  if (preferred.slug === 'ab-wheel-rollout' && !allowAdvancedCore) {
    const safeCore = catalog.find((e) => e.slug === 'dead-bug') ?? preferred;
    return { exercise: safeCore, substitutedFrom: preferred.name };
  }

  // Si se activa equipamiento nuevo superior (ej. barra de dominadas), mejorar tracción vertical automáticamente
  if (
    preferred.movementPattern === 'vertical_pull' &&
    preferred.slug === 'dumbbell-pullover-lat'
  ) {
    if (activeSet.has('pullup_bar')) {
      const pullup = catalog.find((e) => e.slug === 'pull-up-bar-vertical');
      if (pullup) return { exercise: pullup, substitutedFrom: preferred.name };
    }
    if (activeSet.has('cable_pulley')) {
      const pulldown = catalog.find((e) => e.slug === 'cable-lat-pulldown');
      if (pulldown) return { exercise: pulldown, substitutedFrom: preferred.name };
    }
  }

  if (isExerciseCompatibleWithEquipment(preferred.requiredEquipment, activeSet)) {
    return { exercise: preferred };
  }

  // 1. Revisar sustituciones explícitas declaradas en la ficha
  for (const sub of preferred.materialSubstitutions) {
    const candidate = catalog.find((c) => c.slug === sub.replacementSlug);
    if (candidate && isExerciseCompatibleWithEquipment(candidate.requiredEquipment, activeSet)) {
      return { exercise: candidate, substitutedFrom: preferred.name };
    }
  }

  // 2. Buscar en el catálogo el mismo patrón de movimiento compatible
  const samePattern = catalog.find(
    (c) =>
      c.movementPattern === preferred.movementPattern &&
      isExerciseCompatibleWithEquipment(c.requiredEquipment, activeSet) &&
      (allowAdvancedCore || c.difficulty !== 'advanced')
  );
  if (samePattern) {
    return { exercise: samePattern, substitutedFrom: preferred.name };
  }

  // 3. Respaldo universal con peso corporal
  const bodyweightFallback =
    catalog.find(
      (c) =>
        c.category === preferred.category &&
        isExerciseCompatibleWithEquipment(c.requiredEquipment, activeSet)
    ) ?? catalog.find((c) => c.slug === 'pushup-incline-controlled')!;

  return { exercise: bodyweightFallback, substitutedFrom: preferred.name };
}
